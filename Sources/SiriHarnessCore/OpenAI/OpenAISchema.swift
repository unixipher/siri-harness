/// Individual content parts within a multimodal chat message.
public enum MessageContentPart: Codable, Sendable, Equatable {
    case text(String)
    case imageUrl(ImageURL)

    enum CodingKeys: String, CodingKey {
        case type
        case text
        case image_url
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        let type = try container.decode(String.self, forKey: .type)
        if type == "text" {
            let text = try container.decode(String.self, forKey: .text)
            self = .text(text)
        } else if type == "image_url" {
            let img = try container.decode(ImageURL.self, forKey: .image_url)
            self = .imageUrl(img)
        } else {
            let text = (try? container.decode(String.self, forKey: .text)) ?? ""
            self = .text(text)
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        switch self {
        case .text(let str):
            try container.encode("text", forKey: .type)
            try container.encode(str, forKey: .text)
        case .imageUrl(let img):
            try container.encode("image_url", forKey: .type)
            try container.encode(img, forKey: .image_url)
        }
    }
}

