/// A single message entity within a chat completion request or response.
public struct ChatMessage: Codable, Sendable, Equatable {
    public var role: String
    public var content: String
    public var contentParts: [MessageContentPart]?
    public var name: String?
    public var reasoning_content: String?
    public var reasoning: String?
    public var tool_calls: [ToolCall]?
    public var tool_call_id: String?

    enum CodingKeys: String, CodingKey {
        case role
        case content
        case name
        case reasoning_content
        case reasoning
        case tool_calls
        case tool_call_id
    }

    public init(
        role: String,
        content: String,
        contentParts: [MessageContentPart]? = nil,
        name: String? = nil,
        reasoning_content: String? = nil,
        reasoning: String? = nil,
        tool_calls: [ToolCall]? = nil,
        tool_call_id: String? = nil
    ) {
        self.role = role
        self.content = content
        self.contentParts = contentParts
        self.name = name
        self.reasoning_content = reasoning_content
        self.reasoning = reasoning ?? reasoning_content
        self.tool_calls = tool_calls
        self.tool_call_id = tool_call_id
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        self.role = try container.decode(String.self, forKey: .role)
        self.name = try container.decodeIfPresent(String.self, forKey: .name)
        self.reasoning_content = try container.decodeIfPresent(String.self, forKey: .reasoning_content)
        self.reasoning = try container.decodeIfPresent(String.self, forKey: .reasoning) ?? self.reasoning_content
        self.tool_calls = try container.decodeIfPresent([ToolCall].self, forKey: .tool_calls)
        self.tool_call_id = try container.decodeIfPresent(String.self, forKey: .tool_call_id)

        if let stringContent = try? container.decode(String.self, forKey: .content) {
            self.content = stringContent
            self.contentParts = nil
        } else if let parts = try? container.decode([MessageContentPart].self, forKey: .content) {
            self.contentParts = parts
            let textParts = parts.compactMap { part -> String? in
                if case .text(let t) = part { return t }
                return nil
            }
            self.content = textParts.joined(separator: "\n")
        } else {
            self.content = ""
            self.contentParts = nil
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encode(role, forKey: .role)
        if let parts = contentParts, !parts.isEmpty {
            try container.encode(parts, forKey: .content)
        } else {
            try container.encode(content, forKey: .content)
        }
        try container.encodeIfPresent(name, forKey: .name)
        try container.encodeIfPresent(reasoning_content, forKey: .reasoning_content)
        try container.encodeIfPresent(reasoning, forKey: .reasoning)
        try container.encodeIfPresent(tool_calls, forKey: .tool_calls)
        try container.encodeIfPresent(tool_call_id, forKey: .tool_call_id)
    }

    public var textContent: String {
        content
    }

    public var imageUrls: [String] {
        var urls: [String] = []

        if let parts = contentParts {
            for part in parts {
                if case .imageUrl(let img) = part, !urls.contains(img.url) {
                    urls.append(img.url)
                }
            }
        }

        if !content.isEmpty {
            let lines = content.components(separatedBy: .newlines)
            for line in lines {
                let trimmed = line.trimmingCharacters(in: .whitespaces)
                if trimmed.hasPrefix("@image:") {
                    let path = String(trimmed.dropFirst("@image:".count)).trimmingCharacters(in: .whitespaces)
                    if !path.isEmpty && !urls.contains(path) {
                        urls.append(path)
                    }
                }
            }

            // Match image_url: <path> even with spaces (e.g. /Users/.../Application Support/...)
            if let regex = try? NSRegularExpression(pattern: "image_url:\\s*([^\\]\\r\\n]+)") {
                let nsString = content as NSString
                let matches = regex.matches(in: content, range: NSRange(location: 0, length: nsString.length))
                for match in matches {
                    if match.numberOfRanges > 1 {
                        let rawPath = nsString.substring(with: match.range(at: 1)).trimmingCharacters(in: .whitespacesAndNewlines)
                        let cleanPath = rawPath.trimmingCharacters(in: CharacterSet(charactersIn: "\"\'"))
                        if !cleanPath.isEmpty && !urls.contains(cleanPath) {
                            urls.append(cleanPath)
                        }
                    }
                }
            }

            // Match Hermes MEDIA: directive
            if let regex = try? NSRegularExpression(pattern: "MEDIA:\\s*([^\\]\\r\\n]+)") {
                let nsString = content as NSString
                let matches = regex.matches(in: content, range: NSRange(location: 0, length: nsString.length))
                for match in matches {
                    if match.numberOfRanges > 1 {
                        let rawPath = nsString.substring(with: match.range(at: 1)).trimmingCharacters(in: .whitespacesAndNewlines)
                        let cleanPath = rawPath.trimmingCharacters(in: CharacterSet(charactersIn: "\"\'"))
                        if !cleanPath.isEmpty && !urls.contains(cleanPath) {
                            urls.append(cleanPath)
                        }
                    }
                }
            }
        }

        return urls
    }
}

/// Request parameters for chat completions compliant with the OpenAI specification.
public struct ChatCompletionRequest: Codable, Sendable {
    public var model: String?
    public var messages: [ChatMessage]
    public var temperature: Double?
    public var max_tokens: Int?
    public var max_completion_tokens: Int?
    public var stream: Bool?
    public var top_p: Double?
    public var reasoning_effort: String?
    public var tools: [ToolDefinition]?
    public var tool_choice: JSONValue?

    public init(
        model: String? = nil,
        messages: [ChatMessage] = [],
        temperature: Double? = nil,
        max_tokens: Int? = nil,
        max_completion_tokens: Int? = nil,
        stream: Bool? = nil,
        top_p: Double? = nil,
        reasoning_effort: String? = nil,
        tools: [ToolDefinition]? = nil,
        tool_choice: JSONValue? = nil
    ) {
        self.model = model
        self.messages = messages
        self.temperature = temperature
        self.max_tokens = max_tokens
        self.max_completion_tokens = max_completion_tokens
        self.stream = stream
        self.top_p = top_p
        self.reasoning_effort = reasoning_effort
        self.tools = tools
        self.tool_choice = tool_choice
    }

    public var effectiveMaxTokens: Int? {
        max_completion_tokens ?? max_tokens
    }

    public var topP: Double? {
        top_p
    }
}

